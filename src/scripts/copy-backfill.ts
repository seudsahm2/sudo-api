import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { PrismaClient } from '@prisma/client';
import { SITE_COPY_CATALOGUE, placeOf } from '../content/site-copy.catalogue';
import { loadCliEnvironment } from './cli-environment';

/**
 * Puts every key in the site copy catalogue into the database.
 *
 *   npm run content:copy-backfill
 *   npm run content:copy-backfill -- --export ../sudo-hq/src/content/copy-defaults.ts
 *
 * Safe to run on every deploy:
 *   - a key the database does not have is inserted with its catalogue wording;
 *   - a key it already has keeps its value, whatever was typed in admin. Only
 *     the label, help text and grouping are refreshed, so the editor describes
 *     each field the way the current code uses it;
 *   - nothing is ever deleted.
 *
 * `--export <file>` also writes the catalogue as the site's own defaults, so
 * the frontend falls back to exactly the same words as the API.
 */

function exportPath(argv: string[]): string | null {
  const index = argv.findIndex((argument) => argument === '--export');
  if (index !== -1) {
    const value = argv[index + 1];
    if (!value) throw new Error('Missing value for --export');
    return resolve(process.cwd(), value);
  }
  const inline = argv.find((argument) => argument.startsWith('--export='));
  return inline
    ? resolve(process.cwd(), inline.slice('--export='.length))
    : null;
}

function writeFrontendDefaults(path: string) {
  const entries = SITE_COPY_CATALOGUE.map(
    (entry) =>
      `  ${JSON.stringify(entry.key)}: ${JSON.stringify(entry.value)},`,
  ).join('\n');

  const source = `/**
 * Generated by \`npm run content:copy-backfill -- --export\` in sudo-api, from
 * src/content/site-copy.catalogue.ts. Do not edit by hand: change the
 * catalogue and export again.
 *
 * The wording every key falls back to when the API cannot be reached, so the
 * site reads the same with or without it.
 */
export const copyDefaults = {
${entries}
} as const;

export type CopyKey = keyof typeof copyDefaults;
`;

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, source, 'utf8');
  console.log(`Frontend defaults written to ${path}`);
}

async function main() {
  loadCliEnvironment();
  const prisma = new PrismaClient();

  try {
    const existing = new Map(
      (
        await prisma.siteCopy.findMany({
          select: { key: true, deletedAt: true },
        })
      ).map((row) => [row.key, row]),
    );

    let inserted = 0;
    let refreshed = 0;

    for (const [position, entry] of SITE_COPY_CATALOGUE.entries()) {
      const { page, section } = placeOf(entry.key);
      const describe = {
        page,
        section,
        label: entry.label,
        kind: entry.kind ?? 'text',
        helpText: entry.helpText ?? null,
        position,
      };

      if (existing.has(entry.key)) {
        await prisma.siteCopy.update({
          where: { key: entry.key },
          data: describe,
        });
        refreshed += 1;
      } else {
        await prisma.siteCopy.create({
          data: { key: entry.key, value: entry.value, ...describe },
        });
        inserted += 1;
      }
    }

    const unknown = [...existing.keys()].filter(
      (key) => !SITE_COPY_CATALOGUE.some((entry) => entry.key === key),
    );

    console.log(
      `Site copy: ${inserted} inserted, ${refreshed} kept and re-described.`,
    );
    if (unknown.length > 0) {
      console.log(
        `In the database but no longer used by the site (left alone): ${unknown.join(', ')}`,
      );
    }

    const target = exportPath(process.argv.slice(2));
    if (target) writeFrontendDefaults(target);
  } finally {
    await prisma.$disconnect();
  }
}

void main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
